#!/usr/bin/env python3
"""Sprite compiler for BitBeast.

Reads tools/sprites.txt (ASCII art, '#' = lit pixel, '.' = dark pixel) and writes
BitBeast/sprites.h as PROGMEM bitmaps (row-major, MSB = leftmost pixel, rows padded
to whole bytes -- the same format Adafruit_GFX::drawBitmap uses).

Also writes tools/sprite_preview.png so you can eyeball the art (needs Pillow).

Format of sprites.txt:
    @NAME WIDTH HEIGHT
    <HEIGHT rows of WIDTH characters>
Blank lines and lines starting with ';' are ignored.

Usage:  python tools/gen_sprites.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "sprites.txt")
OUT = os.path.join(HERE, "..", "BitBeast", "sprites.h")
PNG = os.path.join(HERE, "sprite_preview.png")


def parse(path):
    sprites = []
    cur = None
    with open(path, encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.rstrip("\n").rstrip()
            if not line or line.startswith(";"):
                continue
            if line.startswith("@"):
                if cur and len(cur["rows"]) != cur["h"]:
                    sys.exit(f"{cur['name']}: expected {cur['h']} rows, got {len(cur['rows'])}")
                parts = line[1:].split()
                cur = {"name": parts[0], "w": int(parts[1]), "h": int(parts[2]), "rows": [], "line": lineno}
                sprites.append(cur)
                continue
            if cur is None:
                sys.exit(f"line {lineno}: pixel row before any @header")
            row = line.strip()
            if len(row) != cur["w"]:
                sys.exit(f"line {lineno} ({cur['name']}): row is {len(row)} wide, expected {cur['w']}")
            if set(row) - set("#."):
                sys.exit(f"line {lineno} ({cur['name']}): only '#' and '.' allowed")
            cur["rows"].append(row)
    if cur and len(cur["rows"]) != cur["h"]:
        sys.exit(f"{cur['name']}: expected {cur['h']} rows, got {len(cur['rows'])}")
    return sprites


def to_bytes(sp):
    out = []
    for row in sp["rows"]:
        for bx in range(0, sp["w"], 8):
            b = 0
            for i in range(8):
                x = bx + i
                if x < sp["w"] and row[x] == "#":
                    b |= 0x80 >> i
            out.append(b)
    return out


def write_header(sprites):
    total = 0
    lines = [
        "// AUTO-GENERATED by tools/gen_sprites.py from tools/sprites.txt -- do not edit by hand.",
        "#pragma once",
        "#include <avr/pgmspace.h>",
        "",
    ]
    for sp in sprites:
        data = to_bytes(sp)
        total += len(data)
        lines.append(f"// {sp['name']} {sp['w']}x{sp['h']}")
        lines.append(f"const uint8_t SPR_{sp['name']}[] PROGMEM = {{")
        for i in range(0, len(data), 16):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append(f"// total sprite bytes: {total}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return total


def write_preview(sprites):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("Pillow not installed; skipping preview")
        return
    scale = 6
    pad = 10
    cols = 6
    cell_w = 16 * scale + pad * 2
    cell_h = 16 * scale + pad * 2 + 12
    rows = (len(sprites) + cols - 1) // cols
    img = Image.new("RGB", (cols * cell_w, rows * cell_h), (10, 20, 30))
    d = ImageDraw.Draw(img)
    for idx, sp in enumerate(sprites):
        cx = (idx % cols) * cell_w + pad
        cy = (idx // cols) * cell_h + pad
        for y, row in enumerate(sp["rows"]):
            for x, ch in enumerate(row):
                color = (120, 220, 255) if ch == "#" else (25, 40, 55)
                d.rectangle([cx + x * scale, cy + y * scale, cx + x * scale + scale - 2, cy + y * scale + scale - 2], fill=color)
        d.text((cx, cy + 16 * scale + 2), sp["name"], fill=(255, 255, 255))
    img.save(PNG)


if __name__ == "__main__":
    sprites = parse(SRC)
    total = write_header(sprites)
    write_preview(sprites)
    print(f"{len(sprites)} sprites, {total} bytes -> {os.path.normpath(OUT)}")
